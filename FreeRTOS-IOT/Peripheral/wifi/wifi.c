extern char RXbuff[2048];

static int WiFi_HasReply(const char *token)
{
	if(token == NULL)
	{
		return 0;
	}

	Uart2_PollRx();

	if(strstr(RXbuff, token) != NULL)
	{
		return 1;
	}
	if(strstr(WiFi_RX_BUF, token) != NULL)
	{
		return 1;
	}
	return 0;
}

static int WiFi_BufferHasStaIp(void)
{
	const char *bufs[2];
	const char *p;
	int b;

	Uart2_PollRx();
	bufs[0] = RXbuff;
	bufs[1] = WiFi_RX_BUF;

	for(b = 0; b < 2; b++)
	{
		p = strstr(bufs[b], "+CIPSTA:ip:\"");
		if(p != NULL)
		{
			if(strstr(p, "0.0.0.0") == NULL && strchr(p + 12, '.') != NULL)
			{
				return 1;
			}
		}
		/* legacy / some firmware */
		if(strstr(bufs[b], "192.168.") != NULL)
		{
			return 1;
		}
		if(strstr(bufs[b], "10.") != NULL && strstr(bufs[b], "+CIPSTA:") != NULL)
		{
			return 1;
		}
	}
	return 0;
}

static char WiFi_QueryStaIp(int timeout_ms)
{
	int left = timeout_ms / 100;

	WiFi_printf("AT+CIPSTA?\r\n");
	while(left-- > 0)
	{
		Delay_Ms(100);
		Uart2_PollRx();
		if(WiFi_BufferHasStaIp())
		{
			return 0;
		}
		if(WiFi_HasReply("FAIL"))
		{
			return 1;
		}
	}
	return 1;
}

static void WiFi_DumpRx(const char *tag)
{
	Uart2_PollRx();
	u1_printf("%s rx_bytes=%u raw=%u\r\n", tag,
	          (unsigned)Uart2_GetAggregateLen(), (unsigned)Usart2_RxCounter);
	if(Uart2_GetAggregateLen() > 0U)
	{
		u1_printf("%s data: %s\r\n", tag, Uart2_GetAggregatePtr());
	}
	else if(Usart2_RxCounter > 0U)
	{
		u1_printf("%s raw: %s\r\n", tag, (char*)Usart2_RxBuff);
	}
	else
	{
		u1_printf("%s data: <empty>, check jumpers for %s\r\n", tag, WiFi_UART_DESC);
	}
}

