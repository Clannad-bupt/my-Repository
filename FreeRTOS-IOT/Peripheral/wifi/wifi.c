char WiFi_JoinAP(int timeout)
{		
	int sec;
	int i;

	(void)WiFi_SendCmd("ATE0", 20);
	(void)WiFi_SendCmd("AT+CWDHCP=1,1", 20);

	USART2_Clear_RxBuff();
	u1_printf("Join AT+CWJAP ssid=%s pass_len=%u\r\n", SSID, (unsigned)strlen(PASS));
	WiFi_printf("AT+CWJAP=\"%s\",\"%s\"\r\n", SSID, PASS);

	for(sec = 0; sec < timeout; sec++)
	{
		for(i = 0; i < 10; i++)
		{
			Delay_Ms(100);
			if(WiFi_HasReply("WIFI GOT IP") || WiFi_BufferHasStaIp())
			{
				u1_printf("\r\nJoin AP OK (IP ready)\r\n");
				return 0;
			}
			if(WiFi_HasReply("WIFI CONNECTED"))
			{
				if(WiFi_QueryStaIp(8000) == 0)
				{
					u1_printf("Join AP OK (connected+IP)\r\n");
					return 0;
				}
			}
			if(WiFi_HasReply("FAIL") && WiFi_HasReply("+CWJAP:"))
			{
				u1_printf("\r\nJoin AT fail, reply: %s\r\n", WiFi_RX_BUF);
				return 1;
			}
		}

		if(((sec + 1U) % 5U) == 0U)
		{
			u1_printf("\r\n[%ds rx=%u] ", sec + 1, (unsigned)Usart2_RxCounter);
			if(Usart2_RxCounter > 0U)
			{
				u1_printf("%.96s\r\n", WiFi_RX_BUF);
			}
			if(WiFi_QueryStaIp(3000) == 0)
			{
				u1_printf("Join AP OK (CIPSTA)\r\n");
				return 0;
			}
		}
		else
		{
			u1_printf("%d ", timeout - sec - 1);
		}
	}

	u1_printf("\r\n");
	if(WiFi_QueryStaIp(8000) == 0)
	{
		u1_printf("Join AP OK (late CIPSTA)\r\n");
		return 0;
	}
	u1_printf("Join timeout, reply: %s\r\n", WiFi_RX_BUF);
	return 1;
}
