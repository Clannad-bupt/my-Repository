char WiFi_Reset(int timeout)
{
	int xtimeout = timeout;
	int retry;

#if (WIFI_UART_INSTANCE == 3)
	USART2_Clear_RxBuff();
	u1_printf("Wait ESP8266 boot (PB10/PB11/3V3 jumpers)...\r\n");
	while(timeout--){
		Delay_Ms(100);
		if(WiFi_HasReply("ready") || WiFi_HasReply("Ready"))
		{
			u1_printf("ESP8266 ready\r\n");
			return 0;
		}
		if((Usart2_RxCounter > 0U) && (((xtimeout - timeout) % 10) == 0))
		{
			u1_printf("rx pending %u: %s\r\n", (unsigned)Usart2_RxCounter, (char*)Usart2_RxBuff);
		}
	}
#else
	USART2_Clear_RxBuff();
	WiFi_printf("AT\r\n");
	retry = 20;
	while(retry--){
		Delay_Ms(100);
		if(WiFi_HasReply("OK"))
		{
			u1_printf("AT OK (no reset needed)\r\n");
			return 0;
		}
	}

	USART2_Clear_RxBuff();
	RESET_IO(1);
	Delay_Ms(100);
	RESET_IO(0);
	Delay_Ms(300);
	RESET_IO(1);
	Delay_Ms(800);

	while(timeout--){
		Delay_Ms(100);
		if(WiFi_HasReply("ready") || WiFi_HasReply("Ready"))
			break;
		u1_printf("timeout = %d ms\r\n", (xtimeout-timeout)*100);
	}

	if(timeout > 0)
	{
		return 0;
	}
#endif

	u1_printf("No ready, try AT...\r\n");
	if(Usart2_RxCounter > 0U)
	{
		u1_printf("bytes before AT retry: %s\r\n", (char*)Usart2_RxBuff);
	}
	WiFi_printf("AT\r\n");
	retry = 30;
	while(retry--){
		Delay_Ms(100);
		if(WiFi_HasReply("OK"))
		{
			u1_printf("AT OK without ready\r\n");
			return 0;
		}
	}

	Uart2_UartDiag("reset fail");
	WiFi_DumpRx("reset fail");
	return 1;
}
