char WiFi_GetIP(int timeout)
{
	char *p;
	char ip[50];
	int left = timeout;

	USART2_Clear_RxBuff();
	WiFi_printf("AT+CIPSTA?\r\n");
	while(left-- > 0){
		Delay_Ms(100);
		Uart2_PollRx();
		if(WiFi_BufferHasStaIp() && WiFi_HasReply("OK"))
		{
			break;
		}
	}
	if(left < 0)
	{
		return 1;
	}

	p = strstr(WiFi_RX_BUF, "+CIPSTA:ip:\"");
	if(p == NULL)
	{
		p = strstr(RXbuff, "+CIPSTA:ip:\"");
	}
	if(p != NULL)
	{
		if(sscanf(p, "+CIPSTA:ip:\"%49[^\"]\"", ip) == 1)
		{
			u1_printf("ESP8266 IP address: %s\r\n", ip);
			return 0;
		}
	}

	/* fallback for older AT firmware */
	USART2_Clear_RxBuff();
	WiFi_printf("AT+CIFSR\r\n");
	while(timeout--){
		Delay_Ms(100);
		Uart2_PollRx();
		if(strstr(WiFi_RX_BUF, "OK") != NULL)
		{
			break;
		}
	}
	if(timeout <= 0)
	{
		return 1;
	}
	p = strstr(WiFi_RX_BUF, "\"");
	if(p != NULL && sscanf(p, "\"%49[^\"]\"", ip) == 1)
	{
		u1_printf("ESP8266 IP address: %s\r\n", ip);
		return 0;
	}
	return 3;
}
