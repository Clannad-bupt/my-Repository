char WiFi_Connect_TCP(const char *host, int port, int timeout)
{	
	int passthrough_timeout = timeout;

	USART2_Clear_RxBuff();
	WiFi_printf("AT+CIPSTART=\"TCP\",\"%s\",%d\r\n", host, port);
	while(timeout-- > 0){
		Delay_Ms(100);
		Uart2_PollRx();
		if(strstr(WiFi_RX_BUF ,"CONNECT"))
			break;
		if(strstr(WiFi_RX_BUF ,"CLOSED"))
			return 1;
		if(strstr(WiFi_RX_BUF ,"ALREADY CONNECTED"))
			return 2;
		u1_printf("%d ",timeout);
	}
	u1_printf("\r\n");
	if(timeout < 0)
	{
		return 3;
	}

	u1_printf("TCP connected, enter passthrough\r\n");
	USART2_Clear_RxBuff();
	WiFi_printf("AT+CIPSEND\r\n");
	while(passthrough_timeout-- > 0){
		Delay_Ms(100);
		Uart2_PollRx();
		if(strstr(WiFi_RX_BUF,"\r\nOK\r\n\r\n>") || strstr(WiFi_RX_BUF,"OK\r\n>") || strstr(WiFi_RX_BUF,">\r\n"))
			break;
		u1_printf("%d ",passthrough_timeout);
	}
	u1_printf("\r\n");
	if(passthrough_timeout < 0)
	{
		u1_printf("TCP passthrough prompt timeout\r\n");
		return 4;
	}
	return 0;
}

